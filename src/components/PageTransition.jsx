import { motion } from 'framer-motion'

// Wraps every routed page for a subtle, consistent transition — kept short
// and understated so navigating between pages doesn't feel like a "showcase".
export default function PageTransition({ children }) {
  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: -8 }}
      transition={{ duration: 0.35, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  )
}
